-- ====================================================================
-- Foreign keys
-- Added NOT VALID (so rows that existed before never block startup), then validated;
-- if old rows violate one, a NOTICE is logged and only new/edited rows are checked.
-- ====================================================================
DO $$
DECLARE
    fk record;
BEGIN
    FOR fk IN SELECT * FROM (VALUES
        -- wamis_core -> wamis_master (by id)
        ('wamis_core.wamis_pretenders', 'fk_pretender_tender_type',
         'FOREIGN KEY (tender_type_id) REFERENCES wamis_master.master_tender_type(id)'),
        ('wamis_core.wamis_pretenders', 'fk_pretender_form_contract',
         'FOREIGN KEY (form_contract_id) REFERENCES wamis_master.master_form_of_contract(id)'),
        ('wamis_core.wamis_pretenders', 'fk_pretender_tender_category',
         'FOREIGN KEY (tender_category_id) REFERENCES wamis_master.master_tender_category(id)'),
        ('wamis_core.wamis_pretenders', 'fk_pretender_product_category',
         'FOREIGN KEY (product_category_id) REFERENCES wamis_master.master_product_category(id)'),
        -- the product category must belong to the tender category on the same row
        ('wamis_core.wamis_pretenders', 'fk_pretender_product_in_category',
         'FOREIGN KEY (product_category_id, tender_category_id) REFERENCES wamis_master.master_product_category(id, tender_category_id)'),
        ('wamis_core.wamis_pretenders', 'fk_pretender_bid_openers',
         'FOREIGN KEY (bid_openers_id) REFERENCES wamis_master.master_bid_openers_type(id)'),
        ('wamis_core.wamis_pretenders', 'fk_pretender_tenderer_class',
         'FOREIGN KEY (tenderer_class_id) REFERENCES wamis_master.master_tenderer_class(id)'),
        -- within wamis_core / wamis_intergation -> wamis_core
        ('wamis_core.wamis_pretender_documents', 'fk_document_pretender',
         'FOREIGN KEY (pretender_id) REFERENCES wamis_core.wamis_pretenders (id) ON DELETE CASCADE'),
        ('wamis_intergation.wamis_integration_transactions', 'fk_txn_pretender',
         'FOREIGN KEY (pretender_id) REFERENCES wamis_core.wamis_pretenders (id) ON DELETE SET NULL'),
        ('wamis_intergation.wamis_integration_audit_events', 'fk_audit_transaction',
         'FOREIGN KEY (transaction_id) REFERENCES wamis_intergation.wamis_integration_transactions (id)')
    ) AS v(tbl, name, def) LOOP
        IF EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conname = fk.name AND c.conrelid = fk.tbl::regclass
                     AND split_part(pg_get_constraintdef(c.oid), ')', 1) <> split_part(fk.def, ')', 1)) THEN
            EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', fk.tbl, fk.name);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = fk.name AND conrelid = fk.tbl::regclass) THEN
            EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I %s NOT VALID', fk.tbl, fk.name, fk.def);
        END IF;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = fk.name AND conrelid = fk.tbl::regclass AND NOT convalidated) THEN
            BEGIN
                EXECUTE format('ALTER TABLE %s VALIDATE CONSTRAINT %I', fk.tbl, fk.name);
            EXCEPTION WHEN foreign_key_violation THEN
                RAISE NOTICE 'Existing rows in % violate %; constraint enforced for new rows only', fk.tbl, fk.name;
            END;
        END IF;
    END LOOP;
END $$;
