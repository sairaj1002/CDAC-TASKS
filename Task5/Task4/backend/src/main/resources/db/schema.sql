-- ====================================================================
-- WAMIS database structure (PostgreSQL, database: wamis)
--
--   wamis_master      : master data from demo_masters_updated.xls (one table per sheet)
--   wamis_core        : the application tables (pre-tenders, documents, dropdown master)
--   wamis_intergation : GePNIC integration transactions and their audit events
--
-- Run by Spring Boot on every startup BEFORE Hibernate (spring.sql.init.schema-locations),
-- followed by db/master-data.sql. Safe to re-run: everything is IF NOT EXISTS / guarded.
-- Tables left in the public schema by earlier versions are moved (with their data).
-- ====================================================================

CREATE SCHEMA IF NOT EXISTS wamis_master;
CREATE SCHEMA IF NOT EXISTS wamis_core;
CREATE SCHEMA IF NOT EXISTS wamis_intergation;

-- --------------------------------------------------------------------
-- One-time move of tables created in "public" / "wamis_core" by earlier versions
-- --------------------------------------------------------------------
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['master_tender_category', 'master_product_category', 'master_tender_type',
                             'master_form_of_contract', 'master_bid_openers_type', 'master_tenderer_class'] LOOP
        IF to_regclass('public.' || t) IS NOT NULL AND to_regclass('wamis_master.' || t) IS NULL THEN
            EXECUTE format('ALTER TABLE public.%I SET SCHEMA wamis_master', t);
        END IF;
    END LOOP;
    FOREACH t IN ARRAY ARRAY['wamis_master_dropdowns', 'wamis_pretenders', 'wamis_pretender_documents'] LOOP
        IF to_regclass('public.' || t) IS NOT NULL AND to_regclass('wamis_core.' || t) IS NULL THEN
            EXECUTE format('ALTER TABLE public.%I SET SCHEMA wamis_core', t);
        END IF;
    END LOOP;
    FOREACH t IN ARRAY ARRAY['wamis_integration_transactions', 'wamis_integration_audit_events'] LOOP
        IF to_regclass('wamis_intergation.' || t) IS NULL THEN
            IF to_regclass('wamis_core.' || t) IS NOT NULL THEN
                EXECUTE format('ALTER TABLE wamis_core.%I SET SCHEMA wamis_intergation', t);
            ELSIF to_regclass('public.' || t) IS NOT NULL THEN
                EXECUTE format('ALTER TABLE public.%I SET SCHEMA wamis_intergation', t);
            END IF;
        END IF;
    END LOOP;
END $$;

-- ====================================================================
-- wamis_master  (every table keyed by an auto-increment id; the sheet value is UNIQUE)
-- ====================================================================

-- Earlier versions keyed these tables by the sheet value itself. They hold no data of
-- their own (db/master-data.sql reloads them from the xls on every startup), so any
-- table whose primary key is not exactly "id" is dropped and rebuilt. CASCADE also drops
-- the old name-based foreign keys on wamis_pretenders; master-data.sql then converts the
-- old pre-tender text columns to the id columns.
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['master_product_category', 'master_tender_category', 'master_tender_type',
                             'master_form_of_contract', 'master_bid_openers_type', 'master_tenderer_class'] LOOP
        IF to_regclass('wamis_master.' || t) IS NOT NULL AND NOT EXISTS (
            SELECT 1 FROM pg_constraint c
             WHERE c.conrelid = to_regclass('wamis_master.' || t) AND c.contype = 'p'
               AND c.conkey = ARRAY[(SELECT attnum FROM pg_attribute
                                      WHERE attrelid = c.conrelid AND attname = 'id')]) THEN
            EXECUTE format('DROP TABLE wamis_master.%I CASCADE', t);
        END IF;
    END LOOP;
END $$;

CREATE TABLE IF NOT EXISTS wamis_master.master_tender_category (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category      VARCHAR(50) NOT NULL UNIQUE,
    description   VARCHAR(255),
    display_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS wamis_master.master_product_category (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100) NOT NULL,
    tender_category_id BIGINT NOT NULL
        CONSTRAINT fk_product_tender_category REFERENCES wamis_master.master_tender_category (id),
    display_order      INT NOT NULL DEFAULT 0,
    -- the same product name may exist under more than one tender category
    CONSTRAINT uq_product_name_category UNIQUE (name, tender_category_id),
    -- target of the composite FK that keeps a pre-tender's product inside its tender category
    CONSTRAINT uq_product_id_category UNIQUE (id, tender_category_id)
);

CREATE TABLE IF NOT EXISTS wamis_master.master_tender_type (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tendertype    VARCHAR(50) NOT NULL UNIQUE,
    description   VARCHAR(255),
    display_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS wamis_master.master_form_of_contract (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formofcontract VARCHAR(100) NOT NULL UNIQUE,
    display_order  INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS wamis_master.master_bid_openers_type (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    botype        VARCHAR(50) NOT NULL UNIQUE,
    bovalue       INT NOT NULL,
    description   VARCHAR(255),
    display_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS wamis_master.master_tenderer_class (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenderclass   VARCHAR(50) NOT NULL UNIQUE,
    description   VARCHAR(255),
    display_order INT NOT NULL DEFAULT 0
);

